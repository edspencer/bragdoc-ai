// The file-format reference, generated from the schemas (Hallway's referenceMarkdown, from Zod's JSON Schema here):
// one table per file, from each field's `.describe()`. docs/data-format.md carries a copy between markers, kept in
// step by `npm run sync:reference` (test/schema.test.ts fails until it's run); PR9's agent guide reuses it.
import { z } from 'zod';
import { AchievementFrontMatterSchema } from './achievement.js';
import { CompanySchema } from './company.js';
import { EvidenceSchema, EvidenceSidecarSchema } from './evidence.js';
import { FoundCandidateSchema } from './found.js';
import { ProfileSchema } from './profile.js';
import { ProjectSchema } from './project.js';
import { RepoSchema } from './repo.js';

interface JsonSchema {
  type?: string | string[];
  description?: string;
  default?: unknown;
  enum?: unknown[];
  format?: string;
  pattern?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  minimum?: number;
  maximum?: number;
}

function typeOf(s: JsonSchema): string {
  if (s.anyOf) return s.anyOf.map(typeOf).filter((t, i, all) => all.indexOf(t) === i).join(' or ');
  if (s.enum) return 'one of the values given';
  if (s.type === 'array') return `list of ${s.items ? typeOf(s.items) : 'values'}`;
  if (s.type === 'null') return 'empty';
  if (s.format === 'date') return 'date';
  if (s.format === 'date-time') return 'date-time';
  if (s.pattern === '^#[0-9a-fA-F]{6}$') return 'colour';
  if (s.pattern?.startsWith('^[0-7]')) return 'id';
  if (s.type === 'integer') return s.minimum !== undefined && s.maximum !== undefined && s.maximum < 1e6 ? `integer ${s.minimum}–${s.maximum}` : 'integer';
  if (s.type === 'object') return 'mapping';
  return String(s.type ?? 'value');
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function table(title: string, schema: z.ZodType, intro: string): string {
  const js = z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' }) as JsonSchema;
  const out = [`### ${title}`, '', intro, '', '| Key | Type | Required | Meaning |', '|-----|------|----------|---------|'];
  for (const [key, p] of Object.entries(js.properties ?? {})) {
    const req = js.required?.includes(key) && p.default === undefined ? 'yes' : p.default !== undefined ? `default \`${JSON.stringify(p.default)}\`` : '';
    out.push(`| \`${key}\` | ${cell(typeOf(p))} | ${cell(req)} | ${cell(p.description ?? '')} |`);
  }
  return out.join('\n');
}

/** The reference for every file BragDoc reads, as markdown. */
export function referenceMarkdown(): string {
  return [
    table('`profile.yaml`', ProfileSchema, 'About you. Onboarding writes it; until it exists, BragDoc shows the welcome.'),
    table('`companies/<id>.yaml`', CompanySchema, 'A company you worked at.'),
    table('`projects/<id>.yaml`', ProjectSchema, 'A project: dates, a colour, optionally a company and linked repos.'),
    table('`repos/<id>.yaml`', RepoSchema, 'A code repository. Give `localPath`, `remoteUrl`, or both.'),
    table(
      '`achievements/YYYY/MM/<id>.md`',
      AchievementFrontMatterSchema,
      'One achievement: these keys as YAML front-matter between `---` lines, then the markdown body. `YYYY/MM` is the month the id was made in, so the file never moves when you change its date.',
    ),
    table('Evidence (an item in `evidence:`)', EvidenceSchema, 'What backs an achievement (or a Found candidate) up.'),
    table('`evidence/<aa>/<sha256>.yaml`', EvidenceSidecarSchema, 'Describes the stored file next to it (`<aa>` is the first two digits of its sha256).'),
    table('`found/<id>.yaml`', FoundCandidateSchema, 'A candidate in Found.'),
  ].join('\n\n');
}

export const REFERENCE_START = '<!-- reference:start (generated by `npm run sync:reference`; edit shared/schema/, not this) -->';
export const REFERENCE_END = '<!-- reference:end -->';

/** `doc` with the text between the reference markers replaced by the current reference. */
export function withReference(doc: string): string {
  const a = doc.indexOf(REFERENCE_START);
  const b = doc.indexOf(REFERENCE_END);
  if (a < 0 || b < a) throw new Error('the reference markers are missing');
  return doc.slice(0, a + REFERENCE_START.length) + '\n\n' + referenceMarkdown() + '\n\n' + doc.slice(b);
}
