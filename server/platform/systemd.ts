// Linux: a systemd user unit, `bragdoc.service` (adapted from Hallway's server/platform/systemd.ts, with Paddock's
// lessons from packages/server/src/cli/service/systemd.ts). The mapping from the LaunchAgent:
//   RunAtLoad          → `[Install] WantedBy=default.target`, and `systemctl --user enable`
//   KeepAlive <true/>  → `Restart=always` (Paddock #872; systemd never restarts a unit it was asked to stop)
//   ThrottleInterval   → `RestartSec=10`
//   the log file       → the journal: a Linux user looks there, `bragdoc service logs` runs journalctl
//
// A user unit, not a system one: it runs as you, with your manager. That manager starts at your first login and stops
// at your last logout, so by default BragDoc stops when you log out (SSH sessions included). `loginctl enable-linger`
// keeps it, and starts it at boot; that's said after an install rather than done, because it changes how the machine
// behaves after you leave it and needs a privilege `bragdoc` otherwise never asks for.
import fs from 'node:fs';
// POSIX paths whatever OS this runs on, so this platform's logic is tested anywhere
import { posix as path } from 'node:path';
import type { Runner } from './runner.js';
import { type ServiceManager, ServiceManagerError, type ServiceStatus, readIfExists, writeIfChanged } from './services.js';
import { SYSTEMD_UNIT, type ServiceSpec } from './spec.js';

/** `%` starts a specifier everywhere in a unit file; `$` an environment variable in ExecStart. */
const pct = (s: string) => s.replace(/%/g, '%%');
const cEscape = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t');

/** One ExecStart word: specifiers and variables escaped, quoted when it has to be (a path with a space in it). */
export function execWord(a: string): string {
  const s = pct(a).replace(/\$/g, '$$$$');
  return s === '' || /[\s"'\\;]/.test(s) ? `"${cEscape(s)}"` : s;
}

/**
 * The unit. Pure: test/fixtures/services/bragdoc.service pins it. No `StandardOutput=`: a user unit's output goes to
 * the journal, which is where a Linux user looks, and a second copy in a file would be two answers to "where are the
 * logs" (Paddock).
 */
export function renderUnit(spec: ServiceSpec): string {
  return [
    `# Generated by BragDoc (${SYSTEMD_UNIT}). \`bragdoc service install\` rewrites it; \`bragdoc service uninstall\` removes it.`,
    `# Node ${spec.node.version}: ${spec.node.path}`,
    '[Unit]',
    `Description=${pct(spec.description)}`,
    'Documentation=https://github.com/edspencer/bragdoc-ai',
    '',
    '[Service]',
    'Type=simple',
    `WorkingDirectory=${pct(spec.cwd)}`,
    `ExecStart=${spec.program.map(execWord).join(' ')}`,
    ...Object.entries(spec.env).map(([k, v]) => `Environment="${cEscape(pct(`${k}=${v}`))}"`),
    'Restart=always',
    'RestartSec=10',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n');
}

/** ExecStart, read back out of a unit BragDoc wrote, as an argv: execWord undone. */
export function parseUnitArgv(text: string): string[] {
  const m = /^ExecStart=(.*)$/m.exec(text);
  if (!m) return [];
  const out: string[] = [];
  const line = m[1]!;
  let i = 0;
  while (i < line.length) {
    if (line[i] === ' ') {
      i++;
      continue;
    }
    let word = '';
    if (line[i] === '"') {
      for (i++; i < line.length && line[i] !== '"'; i++) {
        if (line[i] === '\\' && i + 1 < line.length) {
          const c = line[++i]!;
          word += c === 'n' ? '\n' : c === 't' ? '\t' : c;
        } else word += line[i];
      }
      i++; // the closing quote
    } else for (; i < line.length && line[i] !== ' '; i++) word += line[i];
    out.push(word.replace(/\$\$/g, '$').replace(/%%/g, '%'));
  }
  return out;
}

/** `systemctl --user show -p …` output: KEY=VALUE lines. */
export function parseShow(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const i = line.indexOf('=');
    if (i > 0) out[line.slice(0, i)] = line.slice(i + 1).trim();
  }
  return out;
}

export interface SystemdOptions {
  /** ~/.config/systemd/user (or $XDG_CONFIG_HOME/systemd/user). */
  dir: string;
  run: Runner;
  /** The user's login name, for the enable-linger hint. */
  user: string;
}

const SHOW_PROPS = 'LoadState,ActiveState,SubState,MainPID,ExecMainStatus,ExecMainPID';

export function systemdManager({ dir, run, user }: SystemdOptions): ServiceManager {
  const file = path.join(dir, SYSTEMD_UNIT);

  const systemctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('systemctl', ['--user', ...args]);
    if (r.code === 127) throw new ServiceManagerError("systemctl is not available: BragDoc's service needs systemd's per-user instance (`systemctl --user`)");
    if (/Failed to connect to (user scope )?bus|DBUS_SESSION_BUS_ADDRESS|XDG_RUNTIME_DIR/.test(r.stderr))
      throw new ServiceManagerError(
        `can't reach systemd's per-user instance (${r.stderr.trim()}). Run it from a login session, or check that $XDG_RUNTIME_DIR is set (usually /run/user/$(id -u)).`,
      );
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`systemctl --user ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (): Promise<ServiceStatus> => {
    const text = readIfExists(file);
    const argv = text === null ? [] : parseUnitArgv(text);
    const r = await systemctl(['show', SYSTEMD_UNIT, `--property=${SHOW_PROPS}`], [0, 1, 4]);
    const p = parseShow(r.stdout);
    const running = p.ActiveState === 'active' || p.ActiveState === 'reloading';
    const pid = Number(p.MainPID) || null;
    // ExecMainStatus is the exit status of the last run; meaningless while it's the one running now
    const exited = !running && Number(p.ExecMainPID) > 0;
    return {
      installed: text !== null,
      argv,
      loaded: p.LoadState === 'loaded',
      running,
      pid: running ? pid : null,
      lastExitCode: exited && /^-?\d+$/.test(p.ExecMainStatus ?? '') ? Number(p.ExecMainStatus) : null,
      state: p.ActiveState ? `${p.ActiveState}${p.SubState ? ` (${p.SubState})` : ''}` : null,
    };
  };

  return {
    kind: 'systemd',
    noun: 'systemd user unit',
    name: SYSTEMD_UNIT,
    file,
    lifetime:
      'It starts when you log in (not when the computer boots), and is restarted if it exits.\n' +
      "A user service stops when you log out. To keep it running while you're logged out, and start it at boot,\n" +
      `enable lingering once: loginctl enable-linger ${user}`,
    render: renderUnit,
    parseArgv: parseUnitArgv,
    installCommands: () => ['systemctl --user daemon-reload', `systemctl --user enable --quiet ${SYSTEMD_UNIT}`, `systemctl --user start ${SYSTEMD_UNIT}`],
    async install(spec) {
      fs.mkdirSync(spec.cwd, { recursive: true });
      const changed = writeIfChanged(file, renderUnit(spec));
      // without it the manager keeps serving its cached copy of the old unit, and an upgrade silently changes nothing
      if (changed) await systemctl(['daemon-reload']);
      await systemctl(['enable', '--quiet', SYSTEMD_UNIT]);
      const st = await status();
      await systemctl([st.running && changed ? 'restart' : 'start', SYSTEMD_UNIT]);
      return { changed };
    },
    // start, stop and restart never touch enable/disable: those decide whether it comes back at the next login, a
    // different question from whether it runs now (Paddock). uninstall is where that link is cut.
    async start() {
      await systemctl(['start', SYSTEMD_UNIT]);
    },
    async stop() {
      await systemctl(['stop', SYSTEMD_UNIT], [0, 5]);
    },
    async restart() {
      // an edited unit takes effect, rather than the manager's cached copy
      await systemctl(['daemon-reload']);
      await systemctl(['restart', SYSTEMD_UNIT]);
    },
    status,
    async uninstall() {
      const existed = fs.existsSync(file);
      // 1 / 5: no such unit, which is what was wanted
      await systemctl(['disable', '--now', '--quiet', SYSTEMD_UNIT], [0, 1, 5]);
      fs.rmSync(file, { force: true });
      await systemctl(['daemon-reload']);
      await systemctl(['reset-failed', SYSTEMD_UNIT], [0, 1, 5]);
      return existed;
    },
    logs: () => ({ command: ['journalctl', ['--user', '-u', SYSTEMD_UNIT, '-f']] }),
  };
}
