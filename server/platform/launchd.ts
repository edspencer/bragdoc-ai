// macOS: a launchd LaunchAgent in the gui/<uid> domain (adapted from Hallway's server/platform/launchd.ts, with
// Paddock's lessons from packages/server/src/cli/service/launchd.ts).
//
// An agent, not a daemon (Paddock): a LaunchAgent is bootstrapped when you log in and runs as you; a LaunchDaemon
// starts at boot, as root, before anyone has logged in. BragDoc's data and `gh` login are yours, so it's an agent, and
// the consequence people meet is that **BragDoc starts at login, not at boot**: after a restart nobody logs into, it
// isn't running. Every message about the service says so.
//
// The lifecycle uses the modern launchctl verbs (bootstrap, bootout, kickstart, print), never the legacy load/unload,
// which on a modern macOS are shims that report success where these report the actual error. `stop` is a bootout,
// not `launchctl stop`: with KeepAlive `<true/>` launchd overrules a `stop` and relaunches it at once, whereas a
// booted-out job isn't loaded, so KeepAlive no longer applies. The plist stays, so the next login starts it again.
import fs from 'node:fs';
// POSIX paths whatever OS this runs on, so this platform's logic is tested anywhere
import { posix as path } from 'node:path';
import type { Runner } from './runner.js';
import { type ServiceManager, ServiceManagerError, type ServiceStatus, readIfExists, writeIfChanged } from './services.js';
import { LAUNCHD_LABEL, type ServiceSpec } from './spec.js';

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unxml = (s: string) => s.replace(/&quot;/g, '"').replace(/&gt;/g, '>').replace(/&lt;/g, '<').replace(/&amp;/g, '&');

/**
 * The plist. Pure: test/fixtures/services/bragdoc.plist pins it.
 *
 * KeepAlive is an unconditional `<true/>` (Paddock #872): `{ SuccessfulExit: false }` reads like the polite choice and
 * is a trap, because a clean exit on SIGTERM (sleep, logout, a stray kill) looks to launchd like "it meant to stop".
 * EnvironmentVariables carries PATH and nothing else: a plist is a readable file in your home.
 */
export function renderPlist(spec: ServiceSpec): string {
  const key = (k: string) => `    <key>${k}</key>`;
  const str = (v: string) => `<string>${xml(v)}</string>`;
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    `<!-- Generated by BragDoc (${LAUNCHD_LABEL}). \`bragdoc service install\` rewrites it; \`bragdoc service uninstall\` removes it. -->`,
    `<!-- Node ${xml(spec.node.version)}: ${xml(spec.node.path).replace(/--/g, '- -')} -->`,
    '<plist version="1.0">',
    '  <dict>',
    `${key('Label')}              ${str(LAUNCHD_LABEL)}`,
    key('ProgramArguments'),
    '    <array>',
    ...spec.program.map((a) => `      ${str(a)}`),
    '    </array>',
    `${key('RunAtLoad')}          <true/>`,
    `${key('KeepAlive')}          <true/>`,
    `${key('ThrottleInterval')}   <integer>10</integer>`,
    `${key('WorkingDirectory')}   ${str(spec.cwd)}`,
    `${key('StandardOutPath')}    ${str(spec.log)}`,
    `${key('StandardErrorPath')}  ${str(spec.log)}`,
    key('EnvironmentVariables'),
    '    <dict>',
    ...Object.entries(spec.env).map(([k, v]) => `      <key>${xml(k)}</key>${' '.repeat(Math.max(1, 9 - k.length))}${str(v)}`),
    '    </dict>',
    '  </dict>',
    '</plist>',
    '',
  ];
  return lines.join('\n');
}

/** ProgramArguments, read back out of a plist BragDoc wrote (a regex is enough for a file in a shape we control). */
export function parsePlistArgv(text: string): string[] {
  const block = /<key>ProgramArguments<\/key>\s*<array>([\s\S]*?)<\/array>/.exec(text);
  if (!block) return [];
  return [...block[1]!.matchAll(/<string>([\s\S]*?)<\/string>/g)].map((m) => unxml(m[1]!));
}

/** `launchctl print gui/<uid>/<label>`: the job's top-level `state`, `pid` and `last exit code`. */
export function parseLaunchctlPrint(text: string): { state: string | null; pid: number | null; lastExitCode: number | null } {
  const top = (k: string) => new RegExp(`^\\t${k} = (.+)$`, 'm').exec(text)?.[1]!.trim() ?? null;
  const pid = top('pid');
  const exit = top('last exit code');
  return {
    state: top('state'),
    pid: pid && /^\d+$/.test(pid) ? Number(pid) : null,
    lastExitCode: exit && /^-?\d+$/.test(exit) ? Number(exit) : null,
  };
}

export interface LaunchdOptions {
  /** ~/Library/LaunchAgents. */
  dir: string;
  uid: number;
  run: Runner;
  /** For the bootout → bootstrap retry. */
  sleep?: (ms: number) => Promise<void>;
}

export function launchdManager({ dir, uid, run, sleep = (ms) => new Promise((r) => setTimeout(r, ms)) }: LaunchdOptions): ServiceManager {
  const domain = `gui/${uid}`;
  const target = `${domain}/${LAUNCHD_LABEL}`;
  const file = path.join(dir, `${LAUNCHD_LABEL}.plist`);
  const missing = () => new ServiceManagerError('launchctl is not available: BragDoc runs as a service with launchd on macOS');

  const launchctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('launchctl', args);
    if (r.code === 127) throw missing();
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`launchctl ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (): Promise<ServiceStatus> => {
    const text = readIfExists(file);
    const argv = text === null ? [] : parsePlistArgv(text);
    const r = await run('launchctl', ['print', target]);
    if (r.code === 127) throw missing();
    if (r.code !== 0) return { installed: text !== null, argv, loaded: false, running: false, pid: null, lastExitCode: null, state: null };
    const p = parseLaunchctlPrint(r.stdout);
    return { installed: text !== null, argv, loaded: true, running: p.state === 'running' && p.pid !== null, pid: p.pid, lastExitCode: p.lastExitCode, state: p.state };
  };

  // Right after a bootout the job may still be on its way out, and bootstrap fails with "5: Input/output error";
  // retrying for a few seconds is the usual cure (Hallway). `enable` first: a job someone disabled by hand would
  // otherwise make bootstrap refuse.
  const bootstrap = async () => {
    await launchctl(['enable', target]);
    for (let i = 0; ; i++) {
      const r = await run('launchctl', ['bootstrap', domain, file]);
      if (r.code === 0) return;
      if (r.code === 127) throw missing();
      if (i >= 10) throw new ServiceManagerError(`launchctl bootstrap ${domain} ${file} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
      await sleep(500);
    }
  };

  // exit 3 / 36 / 113: "No such process" / "Could not find service": it wasn't loaded, which is what was wanted
  const bootout = () => launchctl(['bootout', target], [0, 3, 36, 113]);

  return {
    kind: 'launchd',
    noun: 'LaunchAgent',
    name: LAUNCHD_LABEL,
    file,
    lifetime: 'It starts when you log in (not when the computer boots) and is restarted if it exits.',
    render: renderPlist,
    parseArgv: parsePlistArgv,
    installCommands: () => [`launchctl enable ${target}`, `launchctl bootstrap ${domain} ${file}`],
    async install(spec) {
      fs.mkdirSync(spec.cwd, { recursive: true });
      const changed = writeIfChanged(file, renderPlist(spec));
      const st = await status();
      // a changed plist is only read at bootstrap
      if (st.loaded && changed) await bootout();
      if (!st.loaded || changed) await bootstrap(); // RunAtLoad starts it
      else if (!st.running) await launchctl(['kickstart', target]);
      return { changed };
    },
    async start() {
      const st = await status();
      if (st.running) return;
      // a stopped BragDoc was booted out, so it isn't merely idle but absent from the domain; bootstrapping it is what a
      // login does, so `service start` and the next login take the same path
      if (!st.loaded) await bootstrap();
      else await launchctl(['kickstart', target]);
    },
    async stop() {
      await bootout();
    },
    async restart() {
      // not `kickstart -k` alone: it needs the job loaded, so it fails on the case restart most needs, a stopped
      // service; and the plist is re-read on the way up (Paddock)
      await bootout();
      await bootstrap();
      await launchctl(['kickstart', target]);
    },
    status,
    async uninstall() {
      const existed = fs.existsSync(file);
      await bootout();
      fs.rmSync(file, { force: true });
      return existed;
    },
    logs: (spec) => ({ file: spec.log }),
  };
}
